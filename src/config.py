    @classmethod
    def _parse_market_review_region(cls, value: str) -> str:
        """解析 MARKET_REVIEW_REGION；仅 us 为正式取值，legacy cn/both/hk 告警后等同 us"""
        import logging
        log = logging.getLogger(__name__)
        v = (value or "us").strip().lower()
        if v in ("cn", "both", "hk"):
            log.warning(
                "MARKET_REVIEW_REGION=%s 已不再支持 A股/港股复盘，将按 us 处理。",
                v,
            )
            return "us"
        if v == "us":
            return "us"
        log.warning(
            "MARKET_REVIEW_REGION='%s' 无效，已回退为 us（唯一支持值：us）",
            value,
        )
        return "us"

    @classmethod
    def _parse_md2img_engine(cls, value: str) -> str:
        """解析 MD2IMG_ENGINE；非法时回退 wkhtmltoimage（Issue #455）。"""
        v = (value or 'wkhtmltoimage').strip().lower()
        if v in ('wkhtmltoimage', 'markdown-to-file'):
            return v
        if v:
            import logging
            logging.getLogger(__name__).warning(
                f"MD2IMG_ENGINE '{value}' invalid, fallback to 'wkhtmltoimage' "
                "(valid: wkhtmltoimage | markdown-to-file)"
            )
        return 'wkhtmltoimage'

